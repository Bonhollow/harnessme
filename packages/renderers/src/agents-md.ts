import type { Evidence, FactsSnapshot } from "@harnessme/core";
import { protectedMethodsFromDirectives } from "../../core/src/directives.js";
import { referenceDocuments, renderReferenceMap } from "./reference-pack.js";

export const GENERATED_MARKER = "<!-- Generated by HarnessME. Do not edit outside the PENDING section. -->";
export const PENDING_START = "<!-- HARNESSME:PENDING:START -->";
export const PENDING_END = "<!-- HARNESSME:PENDING:END -->";
export const CRITICAL_PATHS_TOKEN = "{{HARNESSME_CRITICAL_PATHS}}";
export const PENDING_TOKEN = "{{HARNESSME_PENDING}}";
export const DIRECTIVES_TOKEN = "{{HARNESSME_DIRECTIVES}}";
export const VERIFIED_CHANGES_TOKEN = "{{HARNESSME_VERIFIED_CHANGES}}";

export function extractPending(content: string): string {
  const start = content.indexOf(PENDING_START);
  const end = content.indexOf(PENDING_END);
  if (start < 0 || end < start) return "";
  const body = content.slice(start + PENDING_START.length, end);
  return body
    .replace(/^\s*### Pending updates[^\n]*\n/um, "")
    .replace(/^(?:Shipped or materially changed|Established or changed a canonical)[\s\S]*?below\.\s*/u, "")
    .trim();
}

/** Keep the always-loaded entrypoint short; the full operating contract lives in the agent pack. */
export function renderEntrypointMd(facts: FactsSnapshot, pending = ""): string {
  const directives = facts.directives.replace(/^# Project directives\s*/u, "").trim();
  const protectedMethods = protectedMethodsFromDirectives(directives);
  const activeGates = facts.criticalPaths.paths.filter((path) => path.status === "active");
  const pendingBody = pending ? `${pending}\n` : "";
  return `${GENERATED_MARKER}\n# Repository instructions\n\nRead [the canonical agent contract](.harnessme/agent-pack/agent.md), then only the task-relevant references and any closer scoped \`AGENTS.md\`. Inspect the current implementation, callers, and tests before editing. Maintainer directives below take precedence over generated guidance.\n\n## Critical changes\n\n${protectedMethods.length ? `Protected methods: ${protectedMethods.map((method) => `\`${method}\``).join(", ")}. Follow the exact maintainer approval rule below before editing.` : "Follow any maintainer approval rule below before editing a protected method."}\n\n${activeGates.length ? `Active path gates are in [CRITICAL.md](.harnessme/CRITICAL.md). Stop for the required approval before editing a protected path; follow the [critical change audit](.harnessme/agent-pack/critical-change-audit.md) afterward.` : "Review proposed gates before changing a shared core contract."}\n\n## Project directives\n\n${directives ? nestDirectiveHeadings(directives) : "No maintainer-authored directives have been recorded."}\n\n## Maintenance\n\nWhen a change establishes or changes a canonical workflow, invariant, extension seam, or validation rule, update the matching reference and add a dated pending note in the same change. Run \`harnessme validate\` when updating that guidance.\n\n${PENDING_START}\n### Pending updates (edit directly — no command needed)\nEstablished or changed a canonical workflow or rule? Add one dated bullet below.\n\n${pendingBody}${PENDING_END}\n`;
}

function citation(evidenceById: Map<string, Evidence>, ids: string[]): string {
  return ids
    .map((id) => evidenceById.get(id))
    .filter((item): item is Evidence => Boolean(item))
    .map((item) => `\`${item.path}:${item.line}\``)
    .join(", ");
}

function occurrences(value: string, needle: string): number {
  return value.split(needle).length - 1;
}

function nestDirectiveHeadings(markdown: string): string {
  let imported = false;
  let fence: string | undefined;
  return markdown.split("\n").map((line) => {
    const marker = line.match(/^\s*(`{3,}|~{3,})/u)?.[1];
    if (marker) {
      if (!fence) fence = marker[0];
      else if (fence === marker[0]) fence = undefined;
      return line;
    }
    if (fence) return line;
    if (/^## Imported from the pre-existing /u.test(line)) {
      imported = true;
      return `#${line}`;
    }
    if (/^## \d{4}-\d{2}-\d{2}\b/u.test(line)) {
      imported = false;
      return `#${line}`;
    }
    const heading = line.match(/^(#{1,6})(\s+.+)$/u);
    if (!heading) return line;
    return `${"#".repeat(Math.min(6, Math.max(3, heading[1]!.length + (imported ? 3 : 1))))}${heading[2]}`;
  }).join("\n");
}

function addAgentPackLinks(markdown: string): string {
  const links = "- [Canonical agent contract](.harnessme/agent-pack/agent.md): Read after this file, then open only the task-relevant references.\n- [Feature navigation](.harnessme/FEATURES.md): Start here to identify the owning feature, implementation paths, dependencies, tests, and protected areas. Run `harnessme context <path>` for one bounded pre-edit context packet.\n- [Architecture and change map](.harnessme/agent-pack/architecture.md): Use for module routing, task guides, and cross-module change rules.\n- [Testing and validation](.harnessme/agent-pack/testing-and-validation.md): Choose focused coverage and the required verification ladder.\n- [Critical change audit](.harnessme/agent-pack/critical-change-audit.md): Required record standard after a developer confirms a protected edit.";
  const missing = links.split("\n").filter((link) => !markdown.includes(link.match(/\]\([^)]+\)/u)?.[0] ?? ""));
  if (!missing.length) return markdown;
  if (markdown.includes("## Reference map")) return markdown.replace("## Reference map", `## Reference map\n\n${missing.join("\n")}`);
  const firstHeadingEnd = markdown.indexOf("\n", markdown.indexOf("# "));
  return firstHeadingEnd >= 0
    ? `${markdown.slice(0, firstHeadingEnd)}\n\n## Reference map\n\n${missing.join("\n")}${markdown.slice(firstHeadingEnd)}`
    : `## Reference map\n\n${missing.join("\n")}\n\n${markdown}`;
}

function removeMissingReferenceLinks(markdown: string, facts: FactsSnapshot): string {
  const generated = new Set(referenceDocuments(facts).map((reference) => `.harnessme/references/${reference.slug}.md`));
  return markdown.replace(/\[([^\]]+)\]\((\.harnessme\/references\/[^)]+\.md)\)/gu,
    (link, label: string, path: string) => generated.has(path) ? link : label);
}

export function renderAgentsMd(facts: FactsSnapshot, pending = ""): string {
  const evidence = new Map(facts.evidence.map((item) => [item.id, item]));
  const operationalStatement = (statement: string, category: string): string => {
    const instruction = statement.includes(";") ? statement.slice(statement.indexOf(";") + 1).trim() : statement;
    if (!/\b(?:detected|present|contains)\b|\b\d+\s+of\s+\d+\b/iu.test(instruction)) {
      return `${instruction.charAt(0).toUpperCase()}${instruction.slice(1)}`;
    }
    const fallbacks: Record<string, string> = {
      "error-handling": "Preserve the established exception propagation and handling pattern in the owning module.",
      oop: "Preserve established base-class, repository, factory, and object-lifecycle contracts.",
      testing: "Update nearby tests when changing behavior.",
      tooling: "Use checked-in repository tasks and configuration for validation."
    };
    return fallbacks[category] ?? "Follow the established local pattern and preserve its public contract.";
  };
  const renderFacts = (categories: string[], empty: string): string => {
    const selected = facts.conventions.facts.filter((fact) => categories.includes(fact.category));
    return selected.length
      ? selected
        .map((fact) => {
          const assisted = fact.evidence.some((id) => evidence.get(id)?.kind === "ai");
          return `- [${assisted ? "AI-assisted, locally verified" : "Observed"}] ${operationalStatement(fact.statement, fact.category)} Evidence: ${citation(evidence, fact.evidence)}.`;
        })
        .join("\n")
      : empty;
  };
  const conventions = renderFacts(["formatting", "naming", "imports"], "- Follow checked-in formatter, linter, and nearby naming patterns.");
  const operatingRules = renderFacts(["error-handling", "oop", "testing", "tooling"], "- Keep changes scoped to the owning module and preserve its public contracts.\n- Update nearby tests when behavior changes.");
  const moduleMap = facts.stack.topLevelModules.length
    ? facts.stack.topLevelModules.map((module) => `- \`${module}/\`: treat this as a module boundary; inspect its local interfaces and tests before changing cross-module behavior.`).join("\n")
    : "- No stable top-level module boundary was detected; follow the nearest existing files and tests.";
  const documentation = facts.stack.documentationPaths?.length
    ? facts.stack.documentationPaths.slice(0, 12).map((path) => `- Read \`${path}\` when the task touches the behavior it describes.`).join("\n")
    : "- No dedicated operating documentation was detected; establish intent from nearby code, tests, and checked-in configuration.";
  const referenceMap = `${addAgentPackLinks("## Reference map").replace("## Reference map", "").trim()}\n${renderReferenceMap(facts)}`.trim();
  const conflicts = facts.documentationConflicts?.length
    ? facts.documentationConflicts.map((item) => item.kind === "contradiction"
      ? `- \`${item.document}:${item.line}\` conflicts with \`${item.implementationPath}:${item.implementationLine}\`: ${item.message} Verify both sides before editing.`
      : `- \`${item.document}:${item.line}\` references missing \`${item.reference}\`. Verify the current implementation and update the documentation before relying on that claim.`).join("\n")
    : "- No documentation-to-code path conflicts were detected.";
  const observedBoundaries = facts.conventions.facts
    .filter((fact) => (fact.category === "oop" && /\b(?:repository|factory|dependency injection|public contract)\b/iu.test(fact.statement))
      || (fact.category === "error-handling" && /\bresult-style\b/iu.test(fact.statement)))
    .flatMap((fact) => fact.evidence.flatMap((id) => {
      const item = evidence.get(id);
      return item ? [{ path: item.path, statement: operationalStatement(fact.statement, fact.category) }] : [];
    }))
    .filter((item, index, items) => items.findIndex((candidate) => candidate.path === item.path) === index)
    .slice(0, 5);
  const validation = facts.stack.validationCommands?.length
    ? facts.stack.validationCommands.map((command) => `- \`${command}\``).join("\n")
    : "- No repository-specific validation command was verified. Inspect checked-in task configuration before running a command.";
  const directiveBody = facts.directives.replace(/^# Project directives\s*/u, "").trim();
  const directives = directiveBody
    ? nestDirectiveHeadings(directiveBody)
    : "No maintainer-authored directives have been recorded.";
  const protectedMethods = protectedMethodsFromDirectives(directiveBody);
  const directivePrelude = directiveBody
    ? `Before editing, read and follow the Project directives below, including any imported AGENTS.md rules. These maintainer rules take precedence over generated guidance.${protectedMethods.length ? `\n\nProtected methods named in those directives: ${protectedMethods.map((method) => `\`${method}\``).join(", ")}. Follow their exact approval rule before editing.` : ""}\n\n`
    : "";
  const firstSteps = "Read `.harnessme/agent-pack/agent.md` after this file, then read only the task-relevant references it maps.\n\n";
  const validationNote = "The commands below are discovered from repository configuration; discovery does not prove they pass on the current baseline. Report failures and whether they predate your change.";
  const pendingBody = pending ? `${pending}\n` : "";
  const activeCritical = facts.criticalPaths.paths.filter((entry) => entry.status === "active");
  const proposedCritical = facts.criticalPaths.paths.filter((entry) => entry.status === "proposed");
  const critical = activeCritical.length
    ? activeCritical.map((entry) => `- \`${entry.glob}\` [${entry.risk ?? "other"}]: ${entry.reason} Approvers: ${entry.approvers.map((item) => `@${item}`).join(", ")} (${entry.source}, active).`).join("\n")
    : "- No critical paths are currently registered.";
  const coreBoundaries = activeCritical.length
    ? critical
    : observedBoundaries.length
      ? observedBoundaries.map((item) => `- \`${item.path}\` is an observed architectural seam. ${item.statement}`).join("\n")
      : "- No explicit core boundary is active. Treat public interfaces and shared module seams as high-impact until their consumers are understood.";
  const workflowTarget = activeCritical[0]?.glob ?? observedBoundaries[0]?.path;
  const primaryWorkflow = workflowTarget
    ? `- For changes to \`${workflowTarget}\`, trace its callers, preserve the stated interface, update affected consumers and tests, then run the validated checks.`
    : "- For behavior changes, edit through the existing owning seam, update affected consumers and nearby tests, then run the validated checks.";
  const proposals = proposedCritical.length
    ? `- ${proposedCritical.length} candidate${proposedCritical.length === 1 ? "" : "s"} await${proposedCritical.length === 1 ? "s" : ""} review in \`.harnessme/critical-paths.yaml\`. These are advisory; no gate applies.`
    : "- No critical-path candidates are awaiting maintainer review.";
  const changes = facts.changes.changes.length
    ? facts.changes.changes.map((change) => `- ${change.date}: ${change.summary} (${change.paths.map((path) => `\`${path}\``).join(", ")}).`).join("\n")
    : "- No verified material changes recorded yet.";
  if (facts.authoredInstructions) {
    const authoredInstructions = facts.authoredInstructions
      .replace(/^## Proposed critical paths[^\n]*\n[\s\S]*?(?=^## |$(?![\s\S]))/gmu, "")
      .replace(/(^## Critical-path safety gate[^\n]*\n)[\s\S]*?(?=\{\{HARNESSME_CRITICAL_PATHS\}\})/mu,
        "$1\nBefore editing any active path listed below, stop and ask the developer for explicit confirmation of the specific files and intended change. Active rules apply now; proposed candidates are advisory until activated. Never self-approve or bypass the gate. After confirmation, follow `.harnessme/agent-pack/critical-change-audit.md` and any maintainer directives.\n\n");
    const managedTokens = [CRITICAL_PATHS_TOKEN, PENDING_TOKEN, DIRECTIVES_TOKEN, VERIFIED_CHANGES_TOKEN];
    if (!managedTokens.every((token) => occurrences(authoredInstructions, token) === 1)) {
      throw new Error("AI-authored instructions must contain each required HarnessME managed placeholder exactly once.");
    }
    const unknownTokens = authoredInstructions.match(/\{\{HARNESSME_[A-Z_]+\}\}/gu)
      ?.filter((token) => !managedTokens.includes(token)) ?? [];
    if (unknownTokens.length) throw new Error(`AI-authored instructions contain unknown managed placeholders: ${unknownTokens.join(", ")}`);
    const pendingSection = `${PENDING_START}\n### Pending updates (edit directly — no command needed)\nEstablished or changed a canonical workflow or rule? Add one dated bullet below.\n\n${pendingBody}${PENDING_END}`;
    const managedCritical = `${critical}\n\n### Proposed critical paths\n\n${proposals}`;
    return removeMissingReferenceLinks(addAgentPackLinks(`${GENERATED_MARKER}\n${authoredInstructions.trim()}\n`
      .replace(/^(# Repository instructions[^\n]*\n)/mu, `$1\n${directivePrelude}${firstSteps.trim()}\n`)
      .replace(/^(## Validation[^\n]*\n)/mu, `$1\n${validationNote}\n`)
      .replace(CRITICAL_PATHS_TOKEN, managedCritical)
      .replace(DIRECTIVES_TOKEN, directives)
      .replace(VERIFIED_CHANGES_TOKEN, changes)
      .replace(PENDING_TOKEN, pendingSection)), facts);
  }
  return `${GENERATED_MARKER}\n# Repository instructions\n\n${directivePrelude}${firstSteps}Use this file as the operating contract for changes in this repository. Prefer repository evidence and maintainer directives over generic assumptions.\n\n## Project purpose\n\n${facts.stack.projectSummary ?? "Determine the intended behavior from repository documentation and nearby tests before changing it."}\n\nUse the checked-in tasks through ${facts.stack.packageManagers.join(", ") || "the repository's configured tooling"}; do not substitute unverified commands.\n\n## Before editing\n\n- Identify the owning module, trace its callers and public contracts, and inspect nearby tests before changing code.\n${documentation}\n\n## Reference map\n\n${referenceMap}\n\n## Repository map\n\n${moduleMap}\n\n## Operating rules\n\n${operatingRules}\n\n${conventions}\n\n## Known documentation conflicts\n\n${conflicts}\n\n## Core boundaries\n\n${coreBoundaries}\n\n## Change workflows\n\n${primaryWorkflow}\n- For public contracts or persisted data, trace compatibility impact and migration or rollback needs before implementation.\n- For a gated core path, obtain explicit developer confirmation before editing and record the approved material change.\n\n## Validation\n\n${validationNote}\n\nRun the relevant configured commands after changing behavior:\n\n${validation}\n\n## Documentation maintenance\n\nUpdate the task-relevant documentation above when a public contract, invariant, workflow, or canonical extension seam changes. Do not replace verified repository guidance with generic advice.\n\n## Critical-path safety gate\n\nBefore editing a path matching any active rule below, stop and ask the developer for explicit confirmation. A draft record is not confirmation. Never approve your own change or bypass the gate. After confirmation, create a draft with \`harnessme critical draft\`; an allowed reviewer must approve the exact staged content, and the approved record plus \`.harnessme/CRITICAL.md\` and \`.harnessme/critical.json\` must ship with the change.\n\n${critical}\n\n## Proposed critical paths\n\nThese heuristic candidates are informational until a maintainer activates them with \`harnessme critical activate <glob>\`.\n\n${proposals}\n\n## Verified material changes\n\n${changes}\n\n## Project directives\n\n${directives}\n\n## Keeping this harness current\n\nAfter establishing or changing a canonical workflow, invariant, extension seam, or validation rule, update the matching guide and add one dated pending bullet. Run \`harnessme validate\` to verify the claim against repository evidence.\n\n${PENDING_START}\n### Pending updates (edit directly — no command needed)\nEstablished or changed a canonical workflow or rule? Add one dated bullet below.\n\n${pendingBody}${PENDING_END}\n`;
}
